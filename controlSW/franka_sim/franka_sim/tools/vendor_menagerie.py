"""Vendor franka_emika_panda and franka_fr3 from mujoco_menagerie into assets/ and write SOURCE.md.

Why: the models are pinned (commit + per-file sha256) so the simulator is reproducible. The download is untrusted
data: files are only copied, never executed or imported.
Usage: ``python -I -m franka_sim.tools.vendor_menagerie --commit <sha|HEAD> --scratch <empty dir> [--dest DIR]``
(run with cwd=controlSW/franka_sim or PYTHONPATH set, since -I ignores PYTHONPATH: pass the script path instead).
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

REPO_URL = "https://github.com/google-deepmind/mujoco_menagerie"
FOLDERS = ("franka_emika_panda", "franka_fr3")
DEFAULT_DEST = Path(__file__).resolve().parents[1] / "assets"


def _git(*args: str, cwd: Path | None = None) -> str:
    r = subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)
    return r.stdout.strip()


def fetch(commit: str, scratch: Path) -> tuple[Path, str]:
    """Clone (blobless, no checkout) into scratch/menagerie and check out only FOLDERS. Returns (clone, full sha)."""
    scratch.mkdir(parents=True, exist_ok=True)
    if any(scratch.iterdir()):
        raise SystemExit(f"scratch dir must be empty: {scratch}")
    clone = scratch / "menagerie"
    _git("clone", "--filter=blob:none", "--no-checkout", REPO_URL, str(clone))
    _git("sparse-checkout", "set", "--no-cone", *[f"/{f}/" for f in FOLDERS], cwd=clone)
    sha = _git("rev-parse", "HEAD" if commit == "HEAD" else f"{commit}^{{commit}}", cwd=clone)
    _git("-c", "advice.detachedHead=false", "checkout", sha, cwd=clone)
    return clone, sha


def copy_and_hash(clone: Path, dest: Path) -> list[tuple[str, int, str]]:
    rows: list[tuple[str, int, str]] = []
    for folder in FOLDERS:
        src = clone / folder
        if not src.is_dir():
            raise SystemExit(f"{folder} not found in the checkout")
        target = dest / folder
        if target.exists():
            shutil.rmtree(target)
        for f in sorted(src.rglob("*")):
            if f.is_symlink() or not f.is_file():
                if f.is_symlink():
                    raise SystemExit(f"refusing symlink in download: {f}")
                continue
            rel = f.relative_to(clone).as_posix()
            out = dest / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(f, out)
            rows.append((rel, out.stat().st_size, hashlib.sha256(out.read_bytes()).hexdigest()))
    return rows


def write_source(dest: Path, sha: str, rows: list[tuple[str, int, str]]) -> None:
    total = sum(r[1] for r in rows)
    lines = [
        "# Vendored mujoco_menagerie models",
        "",
        f"- repo: {REPO_URL}",
        f"- commit: {sha}",
        f"- fetched: {dt.date.today().isoformat()}",
        f"- folders: {', '.join(FOLDERS)} (copied verbatim, all files)",
        f"- files: {len(rows)}",
        f"- total bytes: {total}",
        "",
        "Generated by `franka_sim/tools/vendor_menagerie.py`; verified by `python -m franka_sim check-assets`.",
        "",
        "| relative path | bytes | sha256 |",
        "|---|---|---|",
    ]
    lines += [f"| {rel} | {size} | {digest} |" for rel, size, digest in rows]
    (dest / "SOURCE.md").write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--commit", required=True, help="menagerie commit sha, or HEAD (resolved and recorded)")
    ap.add_argument("--scratch", required=True, help="fresh empty directory for the clone")
    ap.add_argument("--dest", default=str(DEFAULT_DEST), help="assets dir (default: franka_sim/assets)")
    args = ap.parse_args(argv)
    dest = Path(args.dest)
    dest.mkdir(parents=True, exist_ok=True)
    clone, sha = fetch(args.commit, Path(args.scratch))
    rows = copy_and_hash(clone, dest)
    write_source(dest, sha, rows)
    print(f"vendored {len(rows)} files, {sum(r[1] for r in rows) / 1e6:.2f} MB, commit {sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
