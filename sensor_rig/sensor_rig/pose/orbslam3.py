"""ORB-SLAM3 (v1.0 settings format) mono-inertial config + run script for a EuRoC folder from ``euroc.write_euroc``.

ORB-SLAM3 output ``f_<name>.txt`` (SaveTrajectoryEuRoC) holds ns timestamps and Twb = pose of the IMU ("body").
Its world is NOT gravity-aligned: SaveTrajectoryEuRoC re-bases every pose on the first keyframe's IMU frame
(``Trw * pKF->GetPose() * Twb0``), whose tilt is arbitrary. ``pose-import`` therefore gravity-aligns every trajectory
from the episode's IMU by default: ``pose-import --format orbslam3-euroc --frame imu``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from sensor_rig.pose.euroc import scaled_size


def _camera_model_at(rig, camera: str, scale: float):
    cam = rig.cameras[camera]
    model = cam.model
    w, h = scaled_size(cam.resolution, scale)
    if (w, h) != (int(cam.resolution[0]), int(cam.resolution[1])):
        model = model.scaled(w, h)
    return model, w, h


def _matrix(name: str, M: np.ndarray) -> str:
    M = np.asarray(M, dtype=np.float64)
    data = ", ".join(f"{v:.9f}" for v in M.reshape(-1))
    return f"{name}: !!opencv-matrix\n   rows: {M.shape[0]}\n   cols: {M.shape[1]}\n   dt: f\n   data: [{data}]\n"


def write_orbslam3_settings(rig, camera: str, scale: float, path, imu_rate_hz: float | None = None) -> Path:
    model, w, h = _camera_model_at(rig, camera, scale)
    kind = getattr(model, "kind", "")
    lines = ["%YAML:1.0", "---", "# Generated by sensor_rig pose-prep. ORB-SLAM3 settings format v1.0.",
             'File.version: "1.0"', ""]
    if kind == "fisheye-equidistant":
        lines.append('Camera.type: "KannalaBrandt8"')
        dist = [("k1", model.k1), ("k2", model.k2), ("k3", model.k3), ("k4", model.k4)]
    elif kind == "pinhole-radtan":
        lines.append('Camera.type: "PinHole"')
        dist = [("k1", model.k1), ("k2", model.k2), ("p1", model.p1), ("p2", model.p2)]
    else:
        raise ValueError(f"unsupported camera model {kind!r} for ORB-SLAM3")
    for k, v in [("fx", model.fx), ("fy", model.fy), ("cx", model.cx), ("cy", model.cy)] + dist:
        lines.append(f"Camera1.{k}: {float(v):.9f}")
    lines += [
        f"Camera.width: {w}",
        f"Camera.height: {h}",
        f"Camera.fps: {int(round(float(rig.cameras[camera].fps)))}",
        "Camera.RGB: 0",
        "",
        "# Transformation from camera to body-frame (IMU): T_b_c1 = T_imu_cam",
    ]
    lines.append(_matrix("IMU.T_b_c1", rig.T("imu", camera)).rstrip("\n"))
    noise = rig.imu.noise.for_vio()
    rate = imu_rate_hz or float(rig.imu.output_rate_hz)
    lines += [
        "IMU.InsertKFsWhenLost: 0",
        f"IMU.NoiseGyro: {noise.gyroscope_noise_density:.9g}",
        f"IMU.NoiseAcc: {noise.accelerometer_noise_density:.9g}",
        f"IMU.GyroWalk: {noise.gyroscope_random_walk:.9g}",
        f"IMU.AccWalk: {noise.accelerometer_random_walk:.9g}",
        f"IMU.Frequency: {rate:.1f}",
        "",
        # defaults from ORB-SLAM3 Examples/Monocular-Inertial/TUM-VI.yaml
        "ORBextractor.nFeatures: 1500",
        "ORBextractor.scaleFactor: 1.2",
        "ORBextractor.nLevels: 8",
        "ORBextractor.iniThFAST: 20",
        "ORBextractor.minThFAST: 7",
        "",
        "Viewer.KeyFrameSize: 0.05",
        "Viewer.KeyFrameLineWidth: 1.0",
        "Viewer.GraphLineWidth: 0.9",
        "Viewer.PointSize: 2.0",
        "Viewer.CameraSize: 0.08",
        "Viewer.CameraLineWidth: 3.0",
        "Viewer.ViewpointX: 0.0",
        "Viewer.ViewpointY: -0.7",
        "Viewer.ViewpointZ: -3.5",
        "Viewer.ViewpointF: 500.0",
    ]
    path = Path(path)
    path.write_text("\n".join(lines) + "\n")
    return path


def write_run_script(path, seq_dir, settings, name: str) -> Path:
    path = Path(path)
    script = f"""#!/usr/bin/env bash
# Run ORB-SLAM3 mono-inertial on this EuRoC folder. Needs $ORB_SLAM3 = ORB-SLAM3 checkout (built).
# Output: f_{name}.txt (EuRoC format: t[ns] x y z qx qy qz qw, IMU pose in the first keyframe's IMU frame, NOT
# gravity-aligned; pose-import aligns it to gravity from the IMU), then:
#   python -m sensor_rig pose-import --raw <episode> --traj f_{name}.txt --format orbslam3-euroc --frame imu
set -euo pipefail
: "${{ORB_SLAM3:?set ORB_SLAM3 to your ORB-SLAM3 checkout}}"
cd "$(dirname "$0")"
"$ORB_SLAM3/Examples/Monocular-Inertial/mono_inertial_euroc" "$ORB_SLAM3/Vocabulary/ORBvoc.txt" \\
    "{Path(settings).resolve()}" "{Path(seq_dir).resolve()}" "{(Path(seq_dir) / 'times.txt').resolve()}" "{name}"
"""
    path.write_text(script)
    path.chmod(0o755)
    return path
