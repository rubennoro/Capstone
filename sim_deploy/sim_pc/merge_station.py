"""sim_deploy P1: the sim PC's one station file = a base station + stations/start_pose.yaml.

    python -I sim_deploy/sim_pc/merge_station.py BASE START_POSE OUT [OVERLAY ...]

franka_control takes a single `--station` file, so `run.sh` writes the merged file into the gitignored build folder
before every sim PC start (`sim_deploy/build/<base name>.merged.yaml`, e.g. `control_sim.merged.yaml`).

- BASE: `stations/control_sim.yaml` (or a variant such as `control_sim_trainstart.yaml`), used as it is.
- START_POSE: `stations/start_pose.yaml`; it may hold only `franka_control: homing: q_start_rad:` (null or 7 numbers;
  franka_control checks the joint limits itself). Anything else is refused, so the start pose stays the one value
  in that file.
- Merge rule = franka_control's own for station overrides: maps key by key, other values replaced.
- OVERLAY (P4, optional): sim-only station overlays merged last with the same rule (run.sh: the env
  `SIM_DEPLOY_SIM_PC_OVERLAY`, e.g. `stations/homing_fast_sweep.yaml`); they may not set `q_start_rad`.
- `sim.model` / `sim.model_json` are made absolute (resolved against BASE's folder), since OUT lives elsewhere.
"""
from __future__ import annotations

import math
import sys
import time
from pathlib import Path

import yaml


def fail(text: str) -> None:
    sys.exit(f"merge_station: {text}")


def start_pose(path: Path):
    doc = yaml.safe_load(path.read_text())
    if not isinstance(doc, dict) or set(doc) != {"franka_control"}:
        fail(f"{path}: must hold only franka_control: homing: q_start_rad")
    fc = doc["franka_control"]
    if not isinstance(fc, dict) or set(fc) != {"homing"} or not isinstance(fc["homing"], dict) \
            or set(fc["homing"]) != {"q_start_rad"}:
        fail(f"{path}: must hold only franka_control: homing: q_start_rad")
    q = fc["homing"]["q_start_rad"]
    if q is not None:
        if not isinstance(q, list) or len(q) != 7 \
                or not all(isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v) for v in q):
            fail(f"{path}: q_start_rad must be null or 7 numbers (rad)")
        q = [float(v) for v in q]
    return q


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        fail("usage: merge_station.py BASE START_POSE OUT [OVERLAY ...]")
    base_path, pose_path, out_path = (Path(a).expanduser().resolve() for a in argv[:3])
    overlays = [Path(a).expanduser().resolve() for a in argv[3:]]
    base = yaml.safe_load(base_path.read_text())
    if not isinstance(base, dict):
        fail(f"{base_path}: not a station (a YAML map)")
    q = start_pose(pose_path)
    fc = base.setdefault("franka_control", {})
    fc.setdefault("homing", {})["q_start_rad"] = q
    for ov_path in overlays:                       # P4: sim-only overlays, merged key by key
        ov = yaml.safe_load(ov_path.read_text()) or {}
        if not isinstance(ov, dict):
            fail(f"{ov_path}: not a YAML map")
        if ((ov.get("franka_control") or {}).get("homing") or {}).get("q_start_rad", "absent") != "absent":
            fail(f"{ov_path}: an overlay may not set q_start_rad (that is START_POSE's)")

        def merge(dst: dict, src: dict) -> None:
            for k, v in src.items():
                if isinstance(v, dict) and isinstance(dst.get(k), dict):
                    merge(dst[k], v)
                else:
                    dst[k] = v
        merge(base, ov)
    sim = base.get("sim")
    if isinstance(sim, dict):
        for key in ("model", "model_json"):
            if isinstance(sim.get(key), str) and not Path(sim[key]).expanduser().is_absolute():
                sim[key] = str((base_path.parent / sim[key]).resolve())
    head = (f"# GENERATED by sim_deploy/sim_pc/merge_station.py at {time.strftime('%Y-%m-%d %H:%M:%S')}: do not edit.\n"
            f"# = {base_path}\n#   + {pose_path} (franka_control.homing.q_start_rad)\n"
            + "".join(f"#   + {o} (overlay)\n" for o in overlays))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_name(f".{out_path.name}.tmp")
    tmp.write_text(head + yaml.safe_dump(base, sort_keys=False, default_flow_style=None, width=120))
    tmp.replace(out_path)
    print(f"merge_station: {out_path.name}: q_start_rad = {q if q is None else '[' + ', '.join(f'{v:.7f}' for v in q) + ']'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
