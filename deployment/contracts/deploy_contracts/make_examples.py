"""`python -m deploy_contracts.make_examples`: write the C2/C3 examples (with their replies) to examples/.

The files are never edited by hand. A test checks that the committed folder equals what this writes.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from deploy_contracts.examples import INDEX_FILE, INDEX_FORMAT, STORED_CONTRACTS, Example, build_examples
from deploy_contracts.paths import examples_dir

_HEADER = """\
# Generated by `python -m deploy_contracts.make_examples` from deploy_contracts/examples.py. Do not edit by hand.
# One file per example: the exact bytes that travel on the wire (deployment/STRUCTURE.md section 5).
#   valid: true  -> decodes; `values` are scalars a decoder test compares. Keys are value paths: dotted names into
#                   sub-messages (gate.pulled_back), [i] for a list item or array index (O_T_TCP[7][0][3]).
#   valid: false -> refused with exactly this `field` ("" for none) and `problem` code. schema "?" = unreadable.
"""


def _entry(e: Example) -> dict:
    out: dict = {"file": e.file, "schema": e.schema, "valid": e.valid}
    if e.valid:
        if e.values:
            out["values"] = dict(e.values)
    else:
        out["field"] = e.field
        out["problem"] = e.problem
    if e.note:
        out["note"] = e.note
    return out


def index_text(examples: list[Example]) -> str:
    body = yaml.safe_dump({"format": INDEX_FORMAT, "examples": [_entry(e) for e in examples]}, sort_keys=False,
                          default_flow_style=False, width=120, allow_unicode=False)
    return _HEADER + body


def write_examples(out_dir: Path) -> list[Path]:
    """Write every stored example and index.yaml to out_dir, removing stale example files. Returns the files."""
    out_dir = Path(out_dir)
    stored = [e for e in build_examples() if e.stored]
    for contract in STORED_CONTRACTS:
        sub = out_dir / contract
        sub.mkdir(parents=True, exist_ok=True)
        for old in sub.glob("*.msgpack"):
            old.unlink()
    written = []
    for e in stored:
        path = out_dir / e.file
        path.write_bytes(e.data)
        written.append(path)
    index = out_dir / INDEX_FILE
    index.write_text(index_text(stored), encoding="utf-8")
    written.append(index)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m deploy_contracts.make_examples", description=__doc__)
    parser.add_argument("--out", type=Path, default=None,
                        help="folder to write (default: deployment/contracts/examples)")
    args = parser.parse_args(argv)
    out = examples_dir() if args.out is None else args.out
    files = write_examples(out)
    print(f"wrote {len(files) - 1} examples and {INDEX_FILE} to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
